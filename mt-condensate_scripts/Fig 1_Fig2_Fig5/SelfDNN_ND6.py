# ============================================================
# F) Self-channel distance vs source intensity scatter plots
#    One per channel, d <= 5 µm, split by intensity threshold
# ============================================================

# Separate puncta by channel
l1 = [obj for obj in all_puncta if obj.channel == 1]
l3 = [obj for obj in all_puncta if obj.channel == 3]
l4 = [obj for obj in all_puncta if obj.channel == 4]

# Intensity thresholds per channel (mirrors cross-channel thresholds)
intensity_thresholds = {1: 1000, 3: 5000, 4: 4000}


def extract_self_dist(puncta_list):
    """Extract self-channel NN distance and target object from each punctum."""
    records = []
    for p in puncta_list:
        if 'dist' not in p.characteristics:
            continue
        if p.channel not in p.characteristics['dist']:
            continue

        d, tgt = p.characteristics['dist'][p.channel]

        records.append({
            'distance_um': d,
            'source_intensity': p.punctumIntensity,
            'source_size_um': p.majorSize,
            'target_intensity': tgt.punctumIntensity,
            'target_size_um': tgt.majorSize,
        })
    return pd.DataFrame(records)


for ch, ch_puncta, ch_label in [
    (1, l1, 'mtRNA'),
    (3, l3, 'mtRNA_Granule'),
    (4, l4, 'mtDNA'),
]:
    df_ch = extract_self_dist(ch_puncta)
    if df_ch.empty:
        print(f"Channel {ch}: no self-channel NN data found — skipping.")
        continue

    # Flag distance <= 5 um
    df_ch['within_5um'] = df_ch['distance_um'] <= 5

    thresh = intensity_thresholds[ch]
    df_ch['I_class'] = np.where(
        df_ch['source_intensity'] >= thresh,
        f'>={thresh}',
        f'<{thresh}',
    )

    # Save per-channel CSV
    csv_name = f'SelfNN_ch{ch}_distance_vs_intensity.csv'
    df_ch.to_csv(csv_name, index=False)
    print(f"Saved {csv_name}")

    # Subset to d <= 5 um
    df_5 = df_ch[df_ch['within_5um']]
    low_mask = df_5['source_intensity'] < thresh
    high_mask = df_5['source_intensity'] >= thresh

    # ---- Plot: I < threshold ----
    plt.figure()
    plt.scatter(
        df_5.loc[low_mask, 'distance_um'],
        df_5.loc[low_mask, 'source_intensity'],
        s=14, color='#1f77b4',
    )
    plt.xlabel(f'Self-channel {ch} NN distance (µm)')
    plt.ylabel(f'Channel {ch} intensity (a.u.)')
    plt.title(f'Self {ch} vs {ch}: d ≤ 5 µm — intensity < {thresh}')
    plt.xlim(0, 5)
    plt.ylim(0, max(6000, thresh * 2))
    n_low = low_mask.sum()
    plt.text(
        0.05, 0.95, f'n(<{thresh}) = {n_low}',
        transform=plt.gca().transAxes, fontsize=10, va='top',
        bbox=dict(facecolor='white', alpha=0.7, edgecolor='none'),
    )
    plt.savefig(f'SelfNN_ch{ch}_int_lt{thresh}_dle5um.pdf', format='pdf')
    plt.savefig(f'SelfNN_ch{ch}_int_lt{thresh}_dle5um.eps', format='eps')
    plt.show()

    # ---- Plot: I >= threshold ----
    plt.figure()
    plt.scatter(
        df_5.loc[high_mask, 'distance_um'],
        df_5.loc[high_mask, 'source_intensity'],
        s=14, color='#d62728',
    )
    plt.xlabel(f'Self-channel {ch} NN distance (µm)')
    plt.ylabel(f'Channel {ch} intensity (a.u.)')
    plt.title(f'Self {ch} vs {ch}: d ≤ 5 µm — intensity ≥ {thresh}')
    plt.xlim(0, 5)
    plt.ylim(0, max(6000, thresh * 2))
    n_high = high_mask.sum()
    plt.text(
        0.05, 0.95, f'n(≥{thresh}) = {n_high}',
        transform=plt.gca().transAxes, fontsize=10, va='top',
        bbox=dict(facecolor='white', alpha=0.7, edgecolor='none'),
    )
    plt.savefig(f'SelfNN_ch{ch}_int_ge{thresh}_dle5um.pdf', format='pdf')
    plt.savefig(f'SelfNN_ch{ch}_int_ge{thresh}_dle5um.eps', format='eps')
    plt.show()

