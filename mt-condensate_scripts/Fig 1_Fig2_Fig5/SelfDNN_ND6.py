def plot_loghist(x, bins, plot):
    hist, bins = np.histogram(x, bins=bins, range=(0.001, 10))
    logbins = np.logspace(np.log10(bins[0]), np.log10(bins[-1]), len(bins))
    n, hist2, bins2 = plot.hist(x, bins=logbins, alpha=0.5)
    plot.set_xscale('log')
    return n, logbins


