"""
Self-Channel k Nearest Neighbors and Distance Analysis
========================================================
Mirror of the cross-channel distance processing, adapted for
same-channel (self) nearest-neighbor distances.

Assumes the same upstream pipeline:
    output  = drop.condensate(...)
    _, _, distance_dict_list, _, _ = dNN.distanceNN(output, zHeight, False, False)
    self_distance_list, _, objs    = dNN.self_distNN(output, zHeight, False, False)

OBJECT ATTRIBUTE:
  Both cross-channel and self-channel NN are stored in:
      obj.characteristics['dist'][target_ch] -> (distance, target_obj)
  For self-channel, target_ch == obj.channel.

Code was generated by Claude and "the relevant parts were" verified by STP
"""

import numpy as np
import matplotlib.pyplot as plt
import droplet10Jul25_smooth as drop
import distNN20Apr25 as dNN
import pandas as pd
import os

# ============================================================
# 0) Upstream pipeline (same as cross-channel script)
# ============================================================

supdirectory = r'ND6 data'
folders = os.listdir(supdirectory)
sddict_list = []
obl = []
for folder in folders:
    directory = supdirectory + '/' + folder
    zHeight = 0.130
    
    print(folder)
    match int(folder):
        case 1:
            intens = [200, 450, 300]
            zsl = [6, 16]
            pmu = 0.035
        case 2:
            intens = [180, 400, 350]
            zsl = [6, 20]
            pmu = 0.065
        case 3:
            intens = [150, 450, 400]
            zsl = [5, 20]
            pmu = 0.065
        case 4:
            intens = [180, 350, 280]
            zsl = [6, 17]
            pmu = 0.065
        case 5:
            intens = [200, 450, 400]
            zsl = [7, 19]
            pmu = 0.065
        case 6:
            intens = [180, 400, 380]
            zsl = [2, 18]
            pmu = 0.065
        case 7:
            intens = [180, 380, 360]
            zsl = [7, 17]
            pmu = 0.065
        case 8:
            intens = [180, 380, 360]
            zsl = [6, 21]
            pmu = 0.065
    
    output = drop.condensate(directory,
                             pmu,
                             intensities=intens,
                             timesteps=[1],
                             zstacks=zsl,
                             channels=[1, 3, 4],
                             windowsizes=[5],
                             masksizes=[4],
                             backints='Calculated',
                             smooth=False,
                             sigma=1.0,
                             plot = 'Suppress'
                             )
    
    _, _, distance_dict_list, _, _ = dNN.distanceNN(output, zHeight, False, False)
    self_distance_list, _, objs = dNN.self_distNN(output, zHeight, False, False)

    sddict_list.append(self_distance_list[0])
    obl.append(objs[0])
# ============================================================
# Build self_distance_dict  (channel -> [distances])
# ============================================================

self_distance_dict = {}
for sd in sddict_list:
    for key in sd.keys():
        if key in self_distance_dict:
            self_distance_dict[key] += sd[key]
        else:
            self_distance_dict[key] = sd[key]

# Unpadded copy for trimming later
self_distance_dict_raw = {k: list(v) for k, v in self_distance_dict.items()}

# Flatten all puncta from objs
all_puncta = []
for sublist in obl:
    all_puncta += sublist

# ============================================================
# A) FULL self-distance CSV  (wide format)
#    -> SelfChannel_3ChannelImages.csv
# ============================================================

temp = [len(self_distance_dict[key]) for key in self_distance_dict.keys()]
max_len = max(temp)

self_distance_dict_padded = {}
for key in self_distance_dict.keys():
    self_distance_dict_padded[f'self_{key}'] = (
        list(self_distance_dict[key]) + [None] * (max_len - len(self_distance_dict[key]))
    )

df_full_self = pd.DataFrame(self_distance_dict_padded)
df_full_self.to_csv('SelfChannel_3ChannelImages.csv', index=False)
print("Saved full self-channel distances to SelfChannel_3ChannelImages.csv")

# ============================================================
# B) TRIMMED self-distances <= 5 µm  (wide format)
#    -> SelfChannel_3ChannelImages_upto5um.csv
# ============================================================

self_distance_dict_trim = {}
for key, vals in self_distance_dict_raw.items():
    trimmed_vals = [d for d in vals if d <= 5]
    self_distance_dict_trim[f'self_{key}'] = trimmed_vals

temp_trim = [len(v) for v in self_distance_dict_trim.values()]
max_trim = max(temp_trim) if temp_trim else 0

for key in self_distance_dict_trim.keys():
    self_distance_dict_trim[key] = (
        list(self_distance_dict_trim[key]) + [None] * (max_trim - len(self_distance_dict_trim[key]))
    )

df_trim_self = pd.DataFrame(self_distance_dict_trim)
df_trim_self.to_csv('SelfChannel_3ChannelImages_upto5um.csv', index=False)
print("Saved self-channel distances <= 5 um to SelfChannel_3ChannelImages_upto5um.csv")

# ============================================================
# C) LONG-FORMAT: all self-channel NN pairs with d <= 5 µm
#    Keep distance + source/target intensities and sizes
#    -> selfDistNN_upto5um_long.csv
#
#    Self-channel NN is stored in:
#       obj.characteristics['dist'][obj.channel] -> (distance_um, target_obj)
# ============================================================

rows_self_trimmed = []

for src in all_puncta:
    src_ch = src.channel

    # Check that the object has a self-channel NN recorded
    if 'dist' not in src.characteristics:
        continue
    if src_ch not in src.characteristics['dist']:
        continue

    dist_um, tgt_obj = src.characteristics['dist'][src_ch]

    if dist_um <= 5:
        rows_self_trimmed.append({
            'pair': f'{src_ch} vs {src_ch}',
            'channel': src_ch,
            'distance_um': dist_um,
            'source_intensity': src.punctumIntensity,
            'target_intensity': tgt_obj.punctumIntensity,
            'source_size_um': src.majorSize,
            'target_size_um': tgt_obj.majorSize,
        })

df_self_long = pd.DataFrame(rows_self_trimmed)
df_self_long.to_csv('selfDistNN_upto5um_long.csv', index=False)

print("Saved long-format self-channel d<=5um NN table to selfDistNN_upto5um_long.csv")
print("Pairs included:", df_self_long['pair'].unique() if len(df_self_long) else 'none')
print("Total self-channel NN pairs (d<=5um):", len(df_self_long))

# ============================================================
# D) Wide-format self-distance tables with intensity filtering
#    For channel 1: split into >=1000 and <1000 source intensity
#    Channels 3, 4: all d<=5 um entries
#    -> SelfChannel_upto5um_HighInt_ch1.csv
#    -> SelfChannel_upto5um_LowInt_ch1.csv
# ============================================================

self_pairs = ['1 vs 1', '3 vs 3', '4 vs 4']


def build_self_wide_table(df_long, pairs, mode='high'):
    """
    mode = 'high' -> channel 1 self-NN with source_intensity >= 1000
    mode = 'low'  -> channel 1 self-NN with source_intensity < 1000
    Channels 3, 4: all d<=5 um entries (unchanged)
    """
    data = {}

    for p in pairs:
        df_pair = df_long[df_long['pair'] == p]

        if p == '1 vs 1':
            if mode == 'high':
                df_sel = df_pair[df_pair['source_intensity'] >= 1000]
            else:
                df_sel = df_pair[df_pair['source_intensity'] < 1000]
        else:
            df_sel = df_pair

        data[p] = df_sel['distance_um'].tolist()

    # Pad to equal length
    max_len = max(len(v) for v in data.values()) if data else 0
    for k in data:
        if len(data[k]) < max_len:
            data[k] = data[k] + [None] * (max_len - len(data[k]))

    return pd.DataFrame(data)


if len(df_self_long) > 0:
    # HIGH-intensity version
    df_self_high = build_self_wide_table(df_self_long, self_pairs, mode='high')
    df_self_high.to_csv('SelfChannel_upto5um_HighInt_ch1.csv', index=False)
    print("Saved SelfChannel_upto5um_HighInt_ch1.csv")
    print("Counts per self-pair (high):")
    print(df_self_high.count())

    # LOW-intensity version
    df_self_low = build_self_wide_table(df_self_long, self_pairs, mode='low')
    df_self_low.to_csv('SelfChannel_upto5um_LowInt_ch1.csv', index=False)
    print("Saved SelfChannel_upto5um_LowInt_ch1.csv")
    print("Counts per self-pair (low):")
    print(df_self_low.count())
else:
    print("No self-channel NN pairs found within 5 um — skipping intensity-split tables.")

